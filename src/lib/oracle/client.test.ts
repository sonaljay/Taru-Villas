import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
const gateway = 'https://mtcs1pr.hospitality-api.ap-singapore-1.ocs.oraclecloud.com'
const token = () => Response.json({ access_token: 'synthetic-token', expires_in: 28800 })
const empty = () => Response.json({ reservations: { reservationInfo: [], offset: 0, hasMore: false, totalResults: 0 } })
let fetcher: ReturnType<typeof vi.fn>
beforeEach(() => {
  vi.resetModules()
  vi.stubEnv('ORACLE_OHIP_ENVIRONMENT', 'production')
  vi.stubEnv('ORACLE_OHIP_GATEWAY', gateway)
  vi.stubEnv('ORACLE_OHIP_CLIENT_ID', 'test-client')
  vi.stubEnv('ORACLE_OHIP_CLIENT_SECRET', 'test-secret')
  vi.stubEnv('ORACLE_OHIP_APP_KEY', 'test-app')
  vi.stubEnv('ORACLE_OHIP_ENTERPRISE_ID', 'TVPL')
  vi.stubEnv('ORACLE_OHIP_SCOPE', 'urn:opc:hgbu:ws:__myscopes__')
  fetcher = vi.fn()
  vi.stubGlobal('fetch', fetcher)
})
afterEach(() => { vi.unstubAllEnvs(); vi.unstubAllGlobals(); vi.useRealTimers() })
describe('read-only Oracle transport', () => {
  it('uses client credentials and scopes every reservation GET to LO', async () => {
    fetcher.mockResolvedValueOnce(token()).mockResolvedValueOnce(empty())
    const { listReservationPage } = await import('./client')
    const res = await listReservationPage('LO', { fromDate: '2026-10-05', toDate: '2026-10-31', offset: 0, limit: 100 })
    expect(res).toMatchObject({ ok: true, data: { bookings: [] } })
    const [url, init] = fetcher.mock.calls[0]
    expect(url).toBe(`${gateway}/oauth/v1/tokens`)
    expect(init.method).toBe('POST')
    expect(init.headers).toMatchObject({ enterpriseId: 'TVPL', 'x-app-key': 'test-app', Authorization: `Basic ${Buffer.from('test-client:test-secret').toString('base64')}` })
    expect(init.body.toString()).toBe('grant_type=client_credentials&scope=urn%3Aopc%3Ahgbu%3Aws%3A__myscopes__')
    const [dataUrl, dataInit] = fetcher.mock.calls[1]
    expect(new URL(dataUrl).searchParams.get('recentlyAccessed')).toBe('false')
    expect(new URL(dataUrl).searchParams.get('arrivalStartDate')).toBe('2026-10-05')
    expect(dataInit).toMatchObject({ method: 'GET', redirect: 'error', cache: 'no-store', headers: { 'x-hotelid': 'LO', 'x-app-key': 'test-app', Authorization: 'Bearer synthetic-token' } })
    expect(dataInit.signal).toBeInstanceOf(AbortSignal)
  })
  it('rejects write-back without requesting either token or data', async () => {
    const { postPreArrival } = await import('./client')
    expect(await postPreArrival('LO', 'synthetic', { eta: null, comment: 'test' })).toMatchObject({ ok: false, status: 405 })
    expect(fetcher).not.toHaveBeenCalled()
  })
  it('refreshes once after a 401 and stops after a second 401', async () => {
    fetcher.mockResolvedValueOnce(token()).mockResolvedValueOnce(new Response('secret server body', { status: 401 })).mockResolvedValueOnce(token()).mockResolvedValueOnce(new Response('private', { status: 401 }))
    const { listReservationPage } = await import('./client')
    expect(await listReservationPage('LO', { offset: 0, limit: 1 })).toEqual({ ok: false, status: 502, error: 'OHIP HTTP 401' })
    expect(fetcher).toHaveBeenCalledTimes(4)
  })
  it('single-flights authentication and does not reuse cache when credentials change', async () => {
    fetcher.mockImplementation((url: string) => Promise.resolve(url.endsWith('/tokens') ? token() : empty()))
    const { listReservationPage } = await import('./client')
    await Promise.all([listReservationPage('LO', { offset: 0, limit: 1 }), listReservationPage('LO', { offset: 0, limit: 1 })])
    expect(fetcher.mock.calls.filter(([url]) => url.endsWith('/tokens'))).toHaveLength(1)
    vi.stubEnv('ORACLE_OHIP_CLIENT_SECRET', 'changed')
    await listReservationPage('LO', { offset: 0, limit: 1 })
    expect(fetcher.mock.calls.filter(([url]) => url.endsWith('/tokens'))).toHaveLength(2)
  })
  it('does not forward credentials to an unknown gateway or a production gateway in UAT mode', async () => {
    const { testConnection } = await import('./client')
    vi.stubEnv('ORACLE_OHIP_GATEWAY', 'https://example.invalid')
    expect((await testConnection()).ok).toBe(false)
    vi.stubEnv('ORACLE_OHIP_GATEWAY', gateway)
    vi.stubEnv('ORACLE_OHIP_ENVIRONMENT', 'uat')
    expect((await testConnection()).ok).toBe(false)
    expect(fetcher).not.toHaveBeenCalled()
  })
  it('contains errors for malformed JSON and network/timeout failures', async () => {
    const { listReservationPage } = await import('./client')
    fetcher.mockResolvedValueOnce(token()).mockResolvedValueOnce(new Response('not-json'))
    expect(await listReservationPage('LO', { offset: 0, limit: 1 })).toMatchObject({ ok: false, error: 'OHIP invalid response' })
    fetcher.mockRejectedValueOnce(new Error('secret URL'))
    expect(await listReservationPage('LO', { offset: 0, limit: 1 })).toMatchObject({ ok: false, error: 'OHIP network failure' })
  })
  it('rejects invalid hotel, identifiers and date ranges before authentication', async () => {
    const { listReservationPage, readReservation } = await import('./client')
    expect((await listReservationPage('elsewhere', { offset: 0, limit: 1 })).ok).toBe(false)
    expect((await listReservationPage('LO', { fromDate: '2026-02-30', toDate: '2026-03-01', offset: 0, limit: 1 })).ok).toBe(false)
    expect((await readReservation('LO', '../other')).ok).toBe(false)
    expect(fetcher).not.toHaveBeenCalled()
  })
  it('bounds the combined authentication and data request deadline', async () => {
    vi.useFakeTimers()
    fetcher.mockImplementationOnce(async () => { await vi.advanceTimersByTimeAsync(20_001); return token() }).mockResolvedValueOnce(empty())
    const { listReservationPage } = await import('./client')
    expect(await listReservationPage('LO', { offset: 0, limit: 1 })).toMatchObject({ ok: false, error: 'OHIP request timed out' })
    expect(fetcher).toHaveBeenCalledTimes(1)
  })
  it('maps 204 list responses to an empty page', async () => {
    fetcher.mockResolvedValueOnce(token()).mockResolvedValueOnce(new Response(null, { status: 204 }))
    const { listReservationPage } = await import('./client')
    expect(await listReservationPage('LO', { offset: 100, limit: 100 })).toMatchObject({ ok: true, data: { bookings: [], hasMore: false, offset: 100 } })
  })
})
